#!/usr/bin/env bash
# Generate the bootstrap install.sh for the install branch: bootstrap/install.sh with its pin block filled in, so it
# clones a repo at one commit of main. With --publish, commit it as the only file of a branch (the install branch) and
# push that to origin; the install branch workflow (.github/workflows/install-branch.yml) does this after CI passes on
# main. Each commit on the branch pins exactly one commit of main, and the branch never moves to an older one.
#
# Usage: scripts/bootstrap.sh [--repo URL] [--commit REV]                    print the bootstrap
#        scripts/bootstrap.sh --publish BRANCH [--repo URL] [--commit REV]   commit it to BRANCH and push it
# REV defaults to HEAD, and URL to origin's (in https form, so the bootstrap clones without credentials).

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEMPLATE="$REPO_ROOT/bootstrap/install.sh"
PIN_BEGIN="# BEGIN GENERATED PIN: written by scripts/bootstrap.sh"
PIN_END="# END GENERATED PIN"

# shellcheck source=../install/lib/output.sh
source "$REPO_ROOT/install/lib/output.sh"

# Print git URL $1 as https://<host>/<path>.git; local paths are printed as they are.
normalize_repo_url() {
  local url="${1%/}"
  url="${url%.git}"
  case "$url" in
    *://*) url="${url#*://}"; url="${url#*@}" ;;
    *@*:*) url="${url#*@}"; url="${url/://}" ;;
    *)     printf '%s' "$1"; return ;;
  esac
  printf 'https://%s.git' "$url"
}

# Print template $1 with its pin block naming repo $2 and commit $3.
render_bootstrap() {
  local template="$1" repo="$2" commit="$3"
  [[ "$(grep -cxF "$PIN_BEGIN" "$template")" == 1 && "$(grep -cxF "$PIN_END" "$template")" == 1 ]] \
    || error "$template needs exactly one pin block ('$PIN_BEGIN' ... '$PIN_END')"
  awk -v begin="$PIN_BEGIN" -v end="$PIN_END" -v repo="$repo" -v commit="$commit" '
    $0 == begin { print; printf "PINNED_REPO=\"%s\"\nPINNED_COMMIT=\"%s\"\n", repo, commit; skip = 1; next }
    $0 == end { skip = 0 }
    !skip
  ' "$template"
}

# Print the commit that bootstrap text $1 pins, or nothing.
pinned_commit() {
  sed -n 's/^PINNED_COMMIT="\(.*\)"$/\1/p' <<< "$1"
}

# Commit bootstrap text $3, pinning commit $2, as the only file (install.sh) of branch $1 on top of origin's, and push
# it to origin. Does nothing if origin's branch already pins $2 or a later commit.
publish() {
  local branch="$1" commit="$2" bootstrap="$3" parent="" current blob tree new
  if git -C "$REPO_ROOT" ls-remote --exit-code --heads origin "$branch" >/dev/null; then
    git -C "$REPO_ROOT" fetch --quiet origin "refs/heads/$branch"
    parent="$(git -C "$REPO_ROOT" rev-parse FETCH_HEAD)"
    current="$(pinned_commit "$(git -C "$REPO_ROOT" show "$parent:install.sh" 2>/dev/null || true)")"
    if [[ "$current" == "$commit" ]]; then
      info "$branch already pins $commit"
      return
    fi
    if [[ -n "$current" ]] && git -C "$REPO_ROOT" merge-base --is-ancestor "$commit" "$current" 2>/dev/null; then
      info "$branch already pins $current, which comes after $commit"
      return
    fi
  fi
  blob="$(printf '%s\n' "$bootstrap" | git -C "$REPO_ROOT" hash-object -w --stdin)"
  tree="$(printf '100755 blob %s\tinstall.sh\n' "$blob" | git -C "$REPO_ROOT" mktree)"
  new="$(git -C "$REPO_ROOT" commit-tree "$tree" ${parent:+-p "$parent"} \
    -m "install.sh: clone main at ${commit:0:7}" -m "Generated by scripts/bootstrap.sh from $commit.")"
  git -C "$REPO_ROOT" push --quiet origin "$new:refs/heads/$branch"
  info "$branch now pins $commit ($new)"
}

main() {
  local branch="" repo="" rev=HEAD commit bootstrap
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --publish) [[ $# -ge 2 ]] || error "--publish requires a branch"; branch="$2"; shift 2 ;;
      --repo)    [[ $# -ge 2 ]] || error "--repo requires a value"; repo="$2"; shift 2 ;;
      --commit)  [[ $# -ge 2 ]] || error "--commit requires a value"; rev="$2"; shift 2 ;;
      *)         error "Unexpected argument: $1" ;;
    esac
  done
  [[ -n "$repo" ]] || repo="$(normalize_repo_url "$(git -C "$REPO_ROOT" remote get-url origin)")"
  commit="$(git -C "$REPO_ROOT" rev-parse --verify --quiet "$rev^{commit}")" || error "no such commit: $rev"

  bootstrap="$(render_bootstrap "$TEMPLATE" "$repo" "$commit")"
  if [[ -n "$branch" ]]; then
    publish "$branch" "$commit" "$bootstrap"
  else
    printf '%s\n' "$bootstrap"
  fi
}

main "$@"
